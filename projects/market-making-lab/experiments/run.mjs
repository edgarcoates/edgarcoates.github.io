// The same data as a module, so the page can import it without a network request.
fs.writeFileSync(new URL("../results.js", import.meta.url), "// Generated by experiments/run.mjs. Do not edit by hand.\nexport default " + JSON.stringify(out) + ";\n");
for (const r of results) console.log(r.name.padEnd(40), "mean", r.mean, "sd", r.sd, "ratio", r.ratio, "p5", r.p5, "loss", r.lossRate, "|inv|", r.meanAbsInventory, "fills", r.fillsPerEpisode);
const q = (rows) => rows.filter((d) => Math.abs(d.inventory) <= 4).map((d) => `${d.inventory}:${d.bid}/${d.ask}`).join(" ");
console.log("calm    ", q(out.policy.calm));
console.log("volatile", q(out.policy.volatile));
